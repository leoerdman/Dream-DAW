fn read_meter(
    level: &dream_ipc::metering::LockFreeLevel,
) -> crate::commands::payloads::MeterReading {
    crate::commands::payloads::MeterReading {
        rms: level.load_rms(),
        peak: level.load_peak(),
        clipping: level.is_clipping(),
    }
}

