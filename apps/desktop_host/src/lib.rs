/// Initializes and runs the Tauri application.
///
/// Called from `main.rs` (desktop) or the mobile entry point.
#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    env_logger::init();
    let state_managers::RuntimeBootstrap {
        engine_handle,
        project_state,
        clip_pool_state,
        settings_state,
        recording_runtime,
        automation_runtime,
        midi_input_runtime,
        plugin_host_state,
        spectrum_state,
        stream_error_rx,
    } = match state_managers::initialize_runtime() {
        Ok(runtime) => runtime,
        Err(err) => {
            log::error!("Fatal: {err}");
            return;
        }
    };

    tauri::Builder::default()
        .plugin(tauri_plugin_shell::init())
        .plugin(tauri_plugin_dialog::init())
        .manage(engine_handle)
        .manage(project_state)
        .manage(clip_pool_state)
        .manage(settings_state)
        .manage(recording_runtime)
        .manage(automation_runtime)
        .manage(midi_input_runtime)
        .manage(plugin_host_state)
        .manage(spectrum_state)
        .invoke_handler(commands::invoke_handler())
        .setup(move |app| {
            state_managers::configure_app_runtime(app, stream_error_rx);
            Ok(())
        })
        .build(tauri::generate_context!())
        .unwrap_or_else(|err| {
            log::error!("Fatal: failed to build Dream DAW: {err}");
            std::process::exit(1);
        })
        .run(state_managers::shutdown_plugins_on_exit);
}

